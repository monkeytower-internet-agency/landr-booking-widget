const COUNTRY_SET = new Set(COUNTRY_CODES)

/** True for a code in the ISO-3166-1 alpha-2 list (case-insensitive). */
export function isCountryCode(code: string | null | undefined): boolean {
  return !!code && COUNTRY_SET.has(code.trim().toUpperCase())
}

/** Upper-cased valid alpha-2 code, else null. */
export function normalizeCountryCode(
  code: string | null | undefined,
): string | null {
  const c = code?.trim().toUpperCase()
  return c && COUNTRY_SET.has(c) ? c : null
}

/** Localized country name; falls back to the bare code if Intl cannot name it. */
export function countryName(code: string, locale: string): string {
  try {
    const dn = new Intl.DisplayNames([locale], { type: 'region' })
    return dn.of(code) ?? code
  } catch {
    return code
  }
}

/** All countries as {code, name}, sorted by localized name. */
export function countryOptions(
  locale: string,
): { code: string; name: string }[] {
  let collator: Intl.Collator
  try {
    collator = new Intl.Collator(locale)
  } catch {
    collator = new Intl.Collator('en')
  }
  return COUNTRY_CODES.map((code) => ({ code, name: countryName(code, locale) })).sort(
    (a, b) => collator.compare(a.name, b.name),
  )
}
