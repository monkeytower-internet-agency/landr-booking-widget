#!/usr/bin/env python3
"""landr-3a8mh.1: regenerate src/lib/tzCountries.gen.ts from the system tzdata.

IANA zone -> ISO-3166 country, for guessCountry's off-Cloudflare fallback
(no edge /geo there). zone.tab gives the canonical zones; tzdata.zi's link
lines add the legacy aliases browsers still report (Asia/Calcutta, US/Pacific).
Run: python3 scripts/gen-tz-countries.py  (needs /usr/share/zoneinfo)
"""
import pathlib

ZI = pathlib.Path('/usr/share/zoneinfo')
OUT = pathlib.Path(__file__).resolve().parent.parent / 'src/lib/tzCountries.gen.ts'

zones: dict[str, str] = {}
for line in (ZI / 'zone.tab').read_text().splitlines():
    if line.startswith('#') or not line.strip():
        continue
    cc, _coord, tz = line.split('\t')[:3]
    zones[tz] = cc
for line in (ZI / 'tzdata.zi').read_text().splitlines():
    parts = line.split()
    if len(parts) == 3 and parts[0] == 'L' and parts[1] in zones and parts[2] not in zones:
        zones[parts[2]] = zones[parts[1]]

body = ',\n'.join(f"  '{tz}': '{cc}'" for tz, cc in sorted(zones.items()))
OUT.write_text(
    '// GENERATED by scripts/gen-tz-countries.py from the IANA tzdata — do not edit.\n'
    '// landr-3a8mh.1: timezone -> country for guessCountry off Cloudflare.\n'
    f'export const TZ_COUNTRIES: Readonly<Record<string, string>> = {{\n{body},\n}}\n'
)
print(f'{len(zones)} zones -> {OUT}')
